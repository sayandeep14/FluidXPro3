"""Turns the checked fx3 tree into readable Python."""

from __future__ import annotations

import keyword
import re
from typing import Optional

from ... import fxtypes as T
from ... import nodes as A
from ...aliases import INT_RANGES
from ...diagnostics import Diagnostics
from ...fxtypes import Ty

# Python operator precedence (higher binds tighter)
P_LAMBDA, P_IF, P_OR, P_AND, P_NOT, P_CMP, P_BOR, P_BXOR, P_BAND, P_SHIFT, P_ADD, P_MUL, \
    P_UNARY, P_POW, P_POSTFIX, P_ATOM = range(16)

_BIN = {
    "+": ("+", P_ADD), "-": ("-", P_ADD), "*": ("*", P_MUL), "/": ("/", P_MUL), "~/": ("//", P_MUL),
    "%": ("%", P_MUL), "**": ("**", P_POW), "&": ("&", P_BAND), "|": ("|", P_BOR), "^": ("^", P_BXOR),
    "<<": ("<<", P_SHIFT), ">>": (">>", P_SHIFT),
}

# Names the generated code relies on; user names that clash get a trailing `_`.
_PY_RESERVED = set(keyword.kwlist) | set(keyword.softkwlist) | {
    "len", "range", "print", "list", "set", "dict", "tuple", "sum", "min", "max", "abs", "sorted",
    "enumerate", "next", "any", "all", "input", "str", "int", "float", "bool", "isinstance", "super",
    "object", "type", "id", "iter", "zip", "self", "cls", "functools", "reversed", "map", "filter",
    "format", "repr", "hash", "chr", "ord",
}

_ERROR_CLASSES = {"Error", "ValueError", "ParseError", "IOError", "FileNotFound", "PermissionDenied",
                  "NetworkError", "TimeoutError", "ConnectionError", "FormatError", "DbError", "AiError"}


def mangle(name: str) -> str:
    return name + "_" if name in _PY_RESERVED or name.startswith("_rt") else name


class PyEmitter:
    def __init__(self, checker, diags: Diagnostics, source_file: str, overflow_checks: bool = True):
        self.ck = checker
        self.d = diags
        self.src = source_file
        self.overflow = overflow_checks
        self.out: list[str] = []
        self.level = 0
        self.names: dict[int, str] = {}
        self.name_counts: dict[str, int] = {}
        self.subst: dict[int, str] = {}          # Symbol id -> code (implicit variables)
        self.node_subst: dict[int, str] = {}     # node id -> code (switch subject)
        self.loops: list[Optional[A.Stmt]] = []  # enclosing loops (RepeatC with a step needs care)
        self.tmp = 0
        self.in_class: Optional[T.ClassInfo] = None
        self.uses_functools = False

    # ==================================================================
    # Output helpers
    # ==================================================================
    def line(self, text: str = "") -> None:
        self.out.append(("    " * self.level + text) if text else "")

    def indent(self) -> None:
        self.level += 1

    def dedent(self) -> None:
        self.level -= 1

    def temp(self, base: str = "t") -> str:
        self.tmp += 1
        return f"_{base}{self.tmp}"

    def unsupported(self, what: str, span) -> None:
        self.d.error("FX1002", f"{what} is not supported by the Python backend yet", span)

    def name_for(self, sym) -> str:
        key = id(sym)
        if key in self.subst:
            return self.subst[key]
        if key in self.names:
            return self.names[key]
        base = mangle(sym.name)
        if getattr(sym, "shadows", False):
            n = self.name_counts.get(base, 1) + 1
            self.name_counts[base] = n
            name = f"{base}_{n}"
        else:
            name = base
        self.names[key] = name
        return name

    # ==================================================================
    # Program
    # ==================================================================
    def emit_program(self, prog: A.Program) -> str:
        classes = [s for s in prog.stmts if isinstance(s, A.ClassDecl)]
        funcs = [s for s in prog.stmts if isinstance(s, A.FuncDecl)]
        top = [s for s in prog.stmts if not isinstance(s, (A.ClassDecl, A.FuncDecl, A.ImportStmt))]

        body_start = len(self.out)
        for cd in self._parents_first(classes):
            self.emit_class(cd)
            self.line()
            self.line()
        for fd in funcs:
            self.emit_function(fd)
            self.line()
            self.line()
        tests = self.emit_tests()
        entry = self.ck.entry
        self.line('if __name__ == "__main__":')
        self.indent()
        self.line("with _rt.program():")
        self.indent()
        self.emit_stmts(top)
        main = mangle(entry.name) if entry is not None else "None"
        self.line(f"_rt.finish(main={main}, tests={'_FX3_TESTS' if tests else 'None'})")
        self.dedent()
        self.dedent()

        header = [
            f"# Generated by fx3c from {self.src}. Edit the .fx3 file, not this one.",
            "from __future__ import annotations",
            "",
        ]
        if self.uses_functools:
            header.append("import functools")
            header.append("")
        header.append("import fx3rt as _rt")
        if self.ck.std_modules:
            from ...stdlib import MODULES
            names = sorted({t.name for m in self.ck.std_modules for t in MODULES[m]})
            header.append(f"from fx3std import {', '.join(names)}")
        header.append("")
        header.append("")
        return "\n".join(header + self.out[body_start:]).rstrip() + "\n"

    def _parents_first(self, classes: list[A.ClassDecl]) -> list[A.ClassDecl]:
        by_name = {c.name: c for c in classes}
        done: list[A.ClassDecl] = []
        seen: set[str] = set()

        def visit(c: A.ClassDecl) -> None:
            if c.name in seen:
                return
            seen.add(c.name)
            if c.parent and c.parent in by_name:
                visit(by_name[c.parent])
            done.append(c)
        for c in classes:
            visit(c)
        return done

    def emit_tests(self) -> bool:
        entries: list[tuple[str, str]] = []
        for fi in self.ck.tests:
            entries.append((fi.name, mangle(fi.name)))
        for fi, cases in self.ck.examples:
            for k, (ins, out) in enumerate(cases, start=1):
                fname = f"_fx3_example_{fi.name}_{k}"
                args = ", ".join(self.x(a, P_LAMBDA + 1) for a in ins)
                call = f"{self.fn_ref(fi)}({args})"
                self.line(f"def {fname}():")
                self.indent()
                label = f"{fi.name}({', '.join(self.x(a, P_LAMBDA + 1) for a in ins)}): "
                self.line(f"_rt.expect_equal({call}, {self.x(out, P_LAMBDA + 1)}, {label!r})")
                self.dedent()
                self.line()
                entries.append((f"example {k} of {fi.name}", fname))
        if not entries:
            return False
        self.line("_FX3_TESTS = [")
        self.indent()
        for name, fn in entries:
            self.line(f"({name!r}, {fn}),")
        self.dedent()
        self.line("]")
        self.line()
        return True

    def fn_ref(self, fi: T.FuncInfo) -> str:
        if fi.owner:
            return f"{fi.owner}.{mangle(fi.name)}"
        return mangle(fi.name)

    # ==================================================================
    # Classes
    # ==================================================================
    def emit_class(self, cd: A.ClassDecl) -> None:
        ci: T.ClassInfo = cd.info
        saved = self.in_class
        self.in_class = ci
        parent = ""
        if ci.parent:
            parent = f"(_rt.{ci.parent})" if ci.parent in _ERROR_CLASSES else f"({ci.parent})"
        self.line(f"class {ci.name}{parent}:")
        self.indent()
        emitted = False
        # static fields
        for vd in cd.fields:
            for item in vd.items:
                f = ci.fields[item.name]
                if f.static:
                    val = self.store(item.init) if item.init is not None else self.zero_value(f.ty)
                    self.line(f"{mangle(f.name)} = {val}")
                    emitted = True
        # constructors
        explicit = [c for c in ci.ctors if c.decl is not None]
        if not explicit:
            self.emit_auto_ctor(ci, cd)
            emitted = True
        elif len(explicit) == 1:
            self.emit_ctor(ci, cd, explicit[0], as_init=True)
            emitted = True
        else:
            self.emit_field_defaults_method(ci, cd)
            for c in explicit:
                self.emit_ctor(ci, cd, c, as_init=False)
            emitted = True
        for fd in cd.methods:
            fi = fd.info
            if fi is None or fi.is_ctor:
                continue
            if fd.body is None:
                self.line()
                self.line(f"def {mangle(fd.name)}(self, *args):")
                self.indent()
                self.line(f'raise NotImplementedError("{ci.name}.{fd.name} is abstract")')
                self.dedent()
                continue
            self.line()
            self.emit_function(fd, method_of=ci)
            emitted = True
        self.emit_derived(ci)
        if not emitted:
            self.line("pass")
        self.dedent()
        self.in_class = saved

    def _instance_fields(self, ci: T.ClassInfo, cd: A.ClassDecl) -> list[tuple[T.FieldInfo, Optional[A.Expr]]]:
        out = []
        for vd in cd.fields:
            for item in vd.items:
                f = ci.fields[item.name]
                if not f.static:
                    out.append((f, item.init))
        return out

    def _all_instance_fields(self, ci: T.ClassInfo) -> list[tuple[T.FieldInfo, Optional[A.Expr]]]:
        chain = []
        c = ci
        while c is not None:
            chain.append(c)
            c = self.ck.classes.get(c.parent) if c.parent else None
        out = []
        for c in reversed(chain):
            if c.builtin:
                for f in c.fields.values():
                    out.append((f, None))
                continue
            out += self._instance_fields(c, c.decl)
        return out

    def emit_auto_ctor(self, ci: T.ClassInfo, cd: A.ClassDecl) -> None:
        fields = self._all_instance_fields(ci)
        # Keep the field order (calls may pass arguments by position). Python doesn't allow a
        # required parameter after an optional one, so those get a MISSING default too; the
        # checker has already made sure they are always passed.
        params = []
        seen_optional = False
        for f, init in fields:
            hint = self.py_hint(f.ty)
            if f.has_default or seen_optional:
                seen_optional = True
                params.append(f"{mangle(f.name)}: {hint} = _rt.MISSING")
            else:
                params.append(f"{mangle(f.name)}: {hint}")
        self.line(f"def __init__(self{''.join(', ' + p for p in params)}) -> None:")
        self.indent()
        if ci.is_error:
            msg = "'' if message is _rt.MISSING else message" if any(f.name == "message" for f, _ in fields) else "''"
            self.line(f"_rt.Error.__init__(self, {msg})")
        for f, init in fields:
            n = mangle(f.name)
            if f.name == "message" and ci.is_error:
                continue
            value = self.copy_if_needed(n, f.ty)
            if f.has_default:
                default = self.store(init) if init is not None else self.zero_value(f.ty)
                self.line(f"self.{n} = {default} if {n} is _rt.MISSING else {value}")
            else:
                self.line(f"self.{n} = {value}")
        if not fields and not ci.is_error:
            self.line("pass")
        self.dedent()

    def emit_field_defaults(self, ci: T.ClassInfo, cd: A.ClassDecl) -> None:
        if ci.is_error:
            self.line("_rt.Error.__init__(self, '')")
        for f, init in self._instance_fields(ci, cd):
            if init is not None:
                self.line(f"self.{mangle(f.name)} = {self.store(init)}")
            elif f.has_default:
                self.line(f"self.{mangle(f.name)} = {self.zero_value(f.ty)}")

    def emit_field_defaults_method(self, ci: T.ClassInfo, cd: A.ClassDecl) -> None:
        self.line("def _fx_fields(self):")
        self.indent()
        n = len(self.out)
        self.emit_field_defaults(ci, cd)
        if len(self.out) == n:
            self.line("pass")
        self.dedent()

    def emit_ctor(self, ci: T.ClassInfo, cd: A.ClassDecl, fi: T.FuncInfo, as_init: bool) -> None:
        fd: A.FuncDecl = fi.decl
        params = self.param_list(fd, fi)
        self.line()
        if as_init:
            self.line(f"def __init__(self{params}):")
            self.indent()
            self.emit_globals(fd)
            self.emit_param_defaults(fd, fi)
            self.emit_field_defaults(ci, cd)
            self.emit_body(fd.body)
            self.dedent()
        else:
            self.line("@classmethod")
            self.line(f"def {mangle(fd.name)}(cls{params}):")
            self.indent()
            self.line("self = cls.__new__(cls)")
            self.line("self._fx_fields()")
            self.emit_globals(fd)
            self.emit_param_defaults(fd, fi)
            self.emit_body(fd.body)
            self.line("return self")
            self.dedent()

    def emit_derived(self, ci: T.ClassInfo) -> None:
        fields = [f for f, _ in self._all_instance_fields(ci)]
        names = [mangle(f.name) for f in fields]
        tup = "(" + "".join(f"self.{n}, " for n in names) + ")"
        tup_o = "(" + "".join(f"other.{n}, " for n in names) + ")"
        if "eq" in ci.derive:
            self.line()
            self.line("def __eq__(self, other):")
            self.indent()
            self.line(f"return isinstance(other, {ci.name}) and {tup} == {tup_o}")
            self.dedent()
            if "hash" not in ci.derive:
                self.line()
                self.line("__hash__ = None")
        if "hash" in ci.derive:
            self.line()
            self.line("def __hash__(self):")
            self.indent()
            self.line(f"return hash({tup})")
            self.dedent()
        if "order" in ci.derive:
            for op, sym in (("lt", "<"), ("le", "<="), ("gt", ">"), ("ge", ">=")):
                self.line()
                self.line(f"def __{op}__(self, other):")
                self.indent()
                self.line(f"return {tup} {sym} {tup_o}")
                self.dedent()
        if "print" in ci.derive:
            self.line()
            self.line("def __str__(self):")
            self.indent()
            parts = ", ".join(f"{f.name}={{_rt._show_nested(self.{mangle(f.name)})}}" for f in fields)
            self.line(f'return f"{ci.name}({parts})"')
            self.dedent()

    # ==================================================================
    # Functions
    # ==================================================================
    def py_hint(self, t: Ty) -> str:
        k = t.kind
        if T.is_int(t):
            return "int"
        if T.is_float(t):
            return "float"
        if k in ("string", "char"):
            return "str"
        if k == "bool":
            return "bool"
        if k in ("vector", "array"):
            return f"list[{self.py_hint(t.args[0])}]"
        if k == "list":
            return "list"
        if k == "set":
            return f"set[{self.py_hint(t.args[0])}]"
        if k == "map":
            return f"dict[{self.py_hint(t.args[0])}, {self.py_hint(t.args[1])}]"
        if k == "tuple":
            return "tuple[" + ", ".join(self.py_hint(a) for a in t.args) + "]" if t.args else "tuple"
        if k == "maybe":
            return f"{self.py_hint(t.args[0])} | None"
        if k == "duration":
            return "float"
        if k == "class":
            return t.name if t.name not in _ERROR_CLASSES else f"_rt.{t.name}"
        if k == "void":
            return "None"
        if k == "multi":
            return "tuple[" + ", ".join(self.py_hint(a) for a in t.args) + "]"
        return "object"

    def param_list(self, fd: A.FuncDecl, fi: T.FuncInfo) -> str:
        parts = []
        for p, pi in zip(fd.params, fi.params):
            n = self.name_for(p.sym) if p.sym is not None else mangle(p.name)
            hint = self.py_hint(pi.ty if not pi.variadic else T.elem(pi.ty))
            if pi.variadic:
                parts.append(f"*{n}: {hint}")
            elif p.default is not None:
                if self._is_simple_literal(p.default):
                    parts.append(f"{n}: {hint} = {self.x(p.default, P_LAMBDA + 1)}")
                else:
                    parts.append(f"{n}: {hint} = _rt.MISSING")
            else:
                parts.append(f"{n}: {hint}")
        return "".join(", " + p for p in parts)

    @staticmethod
    def _is_simple_literal(e: A.Expr) -> bool:
        return isinstance(e, (A.IntLit, A.FloatLit, A.StrLit, A.CharLit, A.BoolLit, A.NoneLit))

    def emit_param_defaults(self, fd: A.FuncDecl, fi: T.FuncInfo) -> None:
        for p, pi in zip(fd.params, fi.params):
            n = self.name_for(p.sym) if p.sym is not None else mangle(p.name)
            if pi.variadic:
                self.line(f"{n} = list({n})")
            elif p.default is not None and not self._is_simple_literal(p.default):
                self.line(f"if {n} is _rt.MISSING:")
                self.indent()
                self.line(f"{n} = {self.store(p.default)}")
                self.dedent()

    def emit_function(self, fd: A.FuncDecl, method_of: Optional[T.ClassInfo] = None) -> None:
        fi: T.FuncInfo = fd.info
        if fi is None:
            return
        if isinstance(fd.body, A.ActionBody):
            return
        params = self.param_list(fd, fi)
        ret = self.py_hint(fi.return_ty)
        decorators = []
        if "memo" in fi.annots:
            self.uses_functools = True
            decorators.append("@functools.cache")
        first = ""
        if method_of is not None:
            if fi.static:
                decorators.append("@staticmethod")
            else:
                first = "self"
            if "property" in fi.annots:
                decorators.append("@property")
        for dec in decorators:
            self.line(dec)
        sig = (first + params) if first else params[2:]
        self.line(f"def {mangle(fd.name)}({sig}) -> {ret}:")
        self.indent()
        self.emit_globals(fd)
        self.emit_param_defaults(fd, fi)
        if isinstance(fd.body, A.Block):
            self.emit_body(fd.body)
        else:
            if fi.returns:
                self.line(f"return {self.store(fd.body)}")
            else:
                self.line(self.x(fd.body, P_LAMBDA))
        self.dedent()

    def emit_body(self, body: A.Block) -> None:
        if not body.stmts:
            self.line("pass")
            return
        self.emit_stmts(body.stmts)

    def emit_globals(self, fd: A.FuncDecl) -> None:
        found: list[str] = []

        def visit(n) -> None:
            if isinstance(n, (A.Assign, A.IncDec)):
                t = n.target
                if isinstance(t, A.Name) and t.sym is not None and t.sym.module_level and \
                        t.sym.kind == "var":
                    nm = self.name_for(t.sym)
                    if nm not in found:
                        found.append(nm)
            if isinstance(n, A.UnpackDecl):
                return
            if isinstance(n, A.Lambda):
                return
            if isinstance(n, A.Node):
                for v in vars(n).values():
                    if isinstance(v, A.Node):
                        visit(v)
                    elif isinstance(v, list):
                        for it in v:
                            if isinstance(it, A.Node):
                                visit(it)
                            elif isinstance(it, A.Case):
                                for s in it.body:
                                    visit(s)
                            elif isinstance(it, A.Catch):
                                visit(it.body)
                            elif isinstance(it, tuple):
                                for y in it:
                                    if isinstance(y, A.Node):
                                        visit(y)
        if isinstance(fd.body, A.Node):
            visit(fd.body)
        if found:
            self.line("global " + ", ".join(found))

    # ==================================================================
    # Statements
    # ==================================================================
    def emit_stmts(self, stmts: list[A.Stmt]) -> None:
        if not stmts:
            self.line("pass")
            return
        for k, s in enumerate(stmts):
            if isinstance(s, A.Defer):
                rest = stmts[k + 1:]
                self.line("try:")
                self.indent()
                self.emit_stmts(rest)
                self.dedent()
                self.line("finally:")
                self.indent()
                self.emit_stmts(s.body.stmts)
                self.dedent()
                return
            self.emit_stmt(s)

    def emit_block(self, b: A.Block) -> None:
        self.indent()
        self.emit_stmts(b.stmts)
        self.dedent()

    def emit_stmt(self, s: A.Stmt) -> None:
        m = getattr(self, "st_" + type(s).__name__, None)
        if m is None:
            self.unsupported(type(s).__name__, s.span)
            return
        m(s)

    def st_ImportStmt(self, s):
        pass

    def st_FuncDecl(self, s):
        pass

    def st_ClassDecl(self, s):
        pass

    def st_Block(self, s: A.Block):
        self.line("if True:  # block")
        self.emit_block(s)

    def st_VarDecl(self, s: A.VarDecl):
        annots = {a.name: a for a in s.annots}
        for item in s.items:
            sym = item.sym
            if sym is None:
                continue
            n = self.name_for(sym)
            ty = sym.ty
            if item.init is not None:
                if ty.kind == "result":
                    value = f"_rt.capture(lambda: {self.x(item.init, P_LAMBDA)})"
                else:
                    value = self.store(item.init)
            elif "size" in annots:
                size = self.x(annots["size"].args[0], P_MUL + 1)
                if "init" in annots:
                    iv = annots["init"].args[0]
                    if T.is_collection(iv.ty) and iv.ty.kind != "tuple":
                        value = f"[_rt.copy({self.x(iv, P_LAMBDA + 1)}) for _ in range({self.x(annots['size'].args[0], P_LAMBDA + 1)})]"
                    else:
                        value = f"[{self.x(iv, P_LAMBDA + 1)}] * {size}"
                else:
                    value = f"[{self.zero_value(T.elem(ty))}] * {size}"
            elif T.is_collection(ty) and ty.kind != "tuple":
                value = self.zero_value(ty)
            elif ty.kind == "maybe":
                value = "None"
            else:
                continue        # declared now, assigned later
            if "range" in annots and len(annots["range"].args) == 2:
                lo, hi = annots["range"].args
                value = f"_rt.in_range({value}, {self.x(lo, P_LAMBDA + 1)}, {self.x(hi, P_LAMBDA + 1)}, {sym.name!r})"
            self.line(f"{n} = {value}")

    def zero_value(self, t: Ty) -> str:
        k = t.kind
        if T.is_int(t):
            return "0"
        if T.is_float(t):
            return "0.0"
        if k == "bool":
            return "False"
        if k == "string":
            return '""'
        if k == "char":
            return "'\\0'"
        if k in ("vector", "list", "array"):
            return "[]"
        if k == "map":
            return "{}"
        if k == "set":
            return "set()"
        return "None"

    def st_UnpackDecl(self, s: A.UnpackDecl):
        names = []
        for t in s.targets:
            if t.name == "_":
                names.append("_")
            else:
                n = self.name_for(t.sym)
                names.append(("*" + n) if t.rest else n)
        lhs = ", ".join(names) + ("," if len(names) == 1 else "")
        self.line(f"{lhs} = {self.x(s.value, P_LAMBDA)}")

    def _range_wrap(self, target: A.Expr, value: str) -> str:
        if isinstance(target, A.Name) and target.sym is not None:
            ra = target.sym.annots.get("range") if hasattr(target.sym, "annots") else None
            if ra is not None and len(ra.args) == 2:
                lo, hi = ra.args
                return f"_rt.in_range({value}, {self.x(lo, P_LAMBDA + 1)}, {self.x(hi, P_LAMBDA + 1)}, {target.sym.name!r})"
        return value

    def st_Assign(self, s: A.Assign):
        tgt = self.target(s.target)
        if s.op == "=":
            value = self.store(s.value)
            self.line(f"{tgt} = {self._range_wrap(s.target, value)}")
            return
        if s.op == "??=":
            self.line(f"if {tgt} is None:")
            self.indent()
            self.line(f"{tgt} = {self.store(s.value)}")
            self.dedent()
            return
        op = s.op[:-1]
        cur = self.x(s.target, P_POSTFIX)     # read form (map @default aware)
        fake = A.Binary(s.span, op, s.target, s.value)
        fake.ty = getattr(s, "_op_ty", None) or s.target.ty
        code = self.binary_code(fake, cur_code=cur)
        self.line(f"{tgt} = {self._range_wrap(s.target, code)}")

    def st_IncDec(self, s: A.IncDec):
        tgt = self.target(s.target)
        cur = self.x(s.target, P_ADD)
        code = f"{cur} {'+' if s.op == '++' else '-'} 1"
        code = self.int_check(code, s.target.ty)
        self.line(f"{tgt} = {self._range_wrap(s.target, code)}")

    def target(self, e: A.Expr) -> str:
        if isinstance(e, A.Name):
            return self.name_for(e.sym)
        if isinstance(e, A.Index):
            obj = self.x(e.obj, P_POSTFIX)
            if isinstance(e.index, A.RangeExpr):
                return f"{obj}[{self.slice_code(e.index)}]"
            return f"{obj}[{self.x(e.index, P_LAMBDA)}]"
        if isinstance(e, A.Member):
            return f"{self.x(e.obj, P_POSTFIX)}.{mangle(e.name)}"
        return self.x(e, P_ATOM)

    def st_ExprStmt(self, s: A.ExprStmt):
        e = s.expr
        if isinstance(e, A.Call) and e.kind == "bank":
            if self.bank_stmt(e):
                return
        if isinstance(e, A.SwitchExpr):
            self.st_Switch(e.switch)
            return
        self.line(self.x(e, P_LAMBDA))

    def cond_code(self, c: A.Expr) -> str:
        if isinstance(c, A.BindCond):
            n = self.name_for(c.sym)
            return f"({n} := {self.x(c.value, P_LAMBDA + 1)}) is not None"
        return self.x(c, P_LAMBDA + 1)

    def st_If(self, s: A.If):
        self.line(f"if {self.cond_code(s.cond)}:")
        self.emit_block(s.then)
        for c, b in s.elifs:
            self.line(f"elif {self.cond_code(c)}:")
            self.emit_block(b)
        if s.else_ is not None:
            self.line("else:")
            self.emit_block(s.else_)

    def _loop(self, header: str, body: A.Block, node: Optional[A.Stmt] = None) -> None:
        self.line(header)
        self.loops.append(node)
        self.emit_block(body)
        self.loops.pop()

    def st_RepeatTimes(self, s: A.RepeatTimes):
        self._loop(f"for _ in range({self.x(s.count, P_LAMBDA)}):", s.body)

    def st_RepeatWhile(self, s: A.RepeatWhile):
        if s.at_least_once:
            flag = self.temp("first")
            self.line(f"{flag} = True")
            self.line(f"while {flag} or {self.x(s.cond, P_OR + 1)}:")
            self.loops.append(None)
            self.indent()
            self.line(f"{flag} = False")
            self.emit_stmts(s.body.stmts)
            self.dedent()
            self.loops.pop()
            return
        self._loop(f"while {self.x(s.cond, P_LAMBDA)}:", s.body)

    def st_RepeatForever(self, s: A.RepeatForever):
        self._loop("while True:", s.body)

    def st_RepeatEach(self, s: A.RepeatEach):
        names = []
        for t in s.targets:
            names.append("_" if t.name == "_" or t.sym is None else self.name_for(t.sym))
        it = s.iterable
        code = self.iter_code(it)
        if it.ty is not None and it.ty.kind == "map" and len(s.targets) == 2:
            code = f"{self.x(it, P_POSTFIX)}.items()"
        self._loop(f"for {', '.join(names)} in {code}:", s.body)

    def iter_code(self, it: A.Expr) -> str:
        if isinstance(it, A.RangeExpr):
            return self.range_code(it)
        return self.x(it, P_LAMBDA + 1)

    def st_RepeatC(self, s: A.RepeatC):
        fast = self._c_loop_as_range(s)
        if fast is not None:
            var, rng = fast
            self._loop(f"for {var} in {rng}:", s.body)
            return
        if s.init is not None:
            self.emit_stmt(s.init)
        cond = self.x(s.cond, P_LAMBDA) if s.cond is not None else "True"
        self.line(f"while {cond}:")
        self.loops.append(s)
        self.indent()
        self.emit_stmts(s.body.stmts)
        if s.step is not None:
            self.emit_stmt(s.step)
        self.dedent()
        self.loops.pop()

    def _c_loop_as_range(self, s: A.RepeatC) -> Optional[tuple[str, str]]:
        """for (int i = a; i < b; i++)  ->  for i in range(a, b), when the body never changes i."""
        init, cond, step = s.init, s.cond, s.step
        if not (isinstance(init, A.VarDecl) and len(init.items) == 1 and init.items[0].init is not None):
            return None
        sym = init.items[0].sym
        if sym is None or not T.is_int(sym.ty):
            return None
        if not (isinstance(cond, A.Compare) and len(cond.ops) == 1 and isinstance(cond.operands[0], A.Name)
                and cond.operands[0].sym is sym and cond.ops[0] in ("<", "<=", ">", ">=")):
            return None
        delta = None
        if isinstance(step, A.IncDec) and isinstance(step.target, A.Name) and step.target.sym is sym:
            delta = 1 if step.op == "++" else -1
        elif isinstance(step, A.Assign) and isinstance(step.target, A.Name) and step.target.sym is sym and \
                step.op in ("+=", "-=") and isinstance(step.value, A.IntLit):
            delta = step.value.value * (1 if step.op == "+=" else -1)
        if not delta:
            return None
        op = cond.ops[0]
        if (delta > 0 and op not in ("<", "<=")) or (delta < 0 and op not in (">", ">=")):
            return None
        if self._assigns(s.body, sym):
            return None
        start = self.x(init.items[0].init, P_LAMBDA + 1)
        end_e = cond.operands[1]
        if op in ("<", ">"):
            end = self.x(end_e, P_LAMBDA + 1)
        else:
            end = self.x(end_e, P_ADD) + (" + 1" if delta > 0 else " - 1")
        var = self.name_for(sym)
        if delta == 1:
            rng = f"range({start}, {end})"
        else:
            rng = f"range({start}, {end}, {delta})"
        return var, rng

    def _assigns(self, node, sym) -> bool:
        if isinstance(node, (A.Assign, A.IncDec)) and isinstance(node.target, A.Name) and node.target.sym is sym:
            return True
        if isinstance(node, A.Node):
            for v in vars(node).values():
                if isinstance(v, A.Node) and self._assigns(v, sym):
                    return True
                if isinstance(v, list):
                    for it in v:
                        if isinstance(it, A.Node) and self._assigns(it, sym):
                            return True
                        if isinstance(it, A.Case) and any(self._assigns(x, sym) for x in it.body):
                            return True
                        if isinstance(it, tuple) and any(isinstance(y, A.Node) and self._assigns(y, sym) for y in it):
                            return True
        return False

    def st_Stop(self, s):
        self.line("break")

    def st_Skip(self, s):
        loop = self.loops[-1] if self.loops else None
        if isinstance(loop, A.RepeatC) and loop.step is not None:
            self.emit_stmt(loop.step)
        self.line("continue")

    def st_Switch(self, s: A.Switch):
        subj = s.subject
        if not isinstance(subj, (A.Name, A.IntLit, A.StrLit, A.This)):
            t = self.temp("s")
            self.line(f"{t} = {self.x(subj, P_LAMBDA)}")
            self.node_subst[id(subj)] = t
        first = True
        for c in s.cases:
            if c.patterns is None:
                if first:
                    self.line("if True:")
                else:
                    self.line("else:")
            else:
                cond = " or ".join(self.x(cc, P_OR + 1) for cc in c.conds) or "False"
                self.line(f"{'if' if first else 'elif'} {cond}:")
            first = False
            self.indent()
            self.emit_stmts(c.body)
            self.dedent()
        self.node_subst.pop(id(subj), None)

    def st_Try(self, s: A.Try):
        self.line("try:")
        self.emit_block(s.body)
        for c in s.catches:
            cls = c.error_cls.name if c.error_cls is not None else "Error"
            ref = f"_rt.{cls}" if cls in _ERROR_CLASSES else cls
            if c.sym is not None:
                self.line(f"except {ref} as {self.name_for(c.sym)}:")
            else:
                self.line(f"except {ref}:")
            self.emit_block(c.body)
        if s.finally_ is not None:
            self.line("finally:")
            self.emit_block(s.finally_)

    def st_Defer(self, s):
        # handled in emit_stmts (wraps the rest of the block in try/finally)
        pass

    def st_Return(self, s: A.Return):
        if not s.values:
            self.line("return")
        else:
            self.line("return " + ", ".join(self.store(v) for v in s.values))

    def st_Fail(self, s: A.Fail):
        self.line(f"raise {self.x(s.error, P_LAMBDA)}")

    # ==================================================================
    # Expressions
    # ==================================================================
    def x(self, e: A.Expr, min_prec: int) -> str:
        code, prec = self.ex(e)
        return f"({code})" if prec < min_prec else code

    def ex(self, e: A.Expr) -> tuple[str, int]:
        sub = self.node_subst.get(id(e))
        if sub is not None:
            return sub, P_ATOM
        m = getattr(self, "ex_" + type(e).__name__, None)
        if m is None:
            self.unsupported(type(e).__name__, e.span)
            return "None", P_ATOM
        return m(e)

    def copy_if_needed(self, code: str, ty: Optional[Ty]) -> str:
        if ty is not None and T.is_collection(ty) and ty.kind != "tuple":
            return f"_rt.copy({code})"
        return code

    def store(self, e: A.Expr) -> str:
        """Code for a value being stored: collections read from a variable are copied (value semantics)."""
        code = self.x(e, P_LAMBDA + 1)
        if isinstance(e, (A.Name, A.Member, A.Index)) and e.ty is not None and T.is_collection(e.ty) \
                and e.ty.kind != "tuple":
            return f"_rt.copy({code})"
        if isinstance(e, A.RangeExpr) and e.ty is not None and T.is_seq(e.ty):
            return f"list({self.range_code(e)})"
        return code

    def int_check(self, code: str, ty: Optional[Ty]) -> str:
        if not self.overflow or ty is None or not T.is_int(ty):
            return code
        if ty.kind == "int":
            return f"_rt.i64({code})"
        return f"_rt.fit({code}, {ty.kind!r})"

    # ---- literals --------------------------------------------------------
    def ex_IntLit(self, e: A.IntLit):
        if e.ty is not None and T.is_float(e.ty):
            return f"{float(e.value)!r}", P_ATOM
        return (str(e.value), P_ATOM) if e.value >= 0 else (str(e.value), P_UNARY)

    def ex_DurationLit(self, e: A.DurationLit):
        return repr(float(e.seconds)), P_ATOM

    def ex_FloatLit(self, e: A.FloatLit):
        r = repr(e.value)
        if r in ("inf", "-inf", "nan"):
            return f"float({r!r})", P_POSTFIX
        return r, P_ATOM if e.value >= 0 else P_UNARY

    def ex_StrLit(self, e: A.StrLit):
        return repr(e.value), P_ATOM

    def ex_CharLit(self, e: A.CharLit):
        return repr(e.value), P_ATOM

    def ex_BoolLit(self, e: A.BoolLit):
        return ("True" if e.value else "False"), P_ATOM

    def ex_NoneLit(self, e):
        return "None", P_ATOM

    _NEEDS_SHOW = {"bool", "none", "maybe", "vector", "list", "array", "map", "set", "tuple", "result",
                   "unknown", "any"}

    def ex_FString(self, e: A.FString):
        pieces: list[tuple[str, str]] = []     # ("text", s) | ("expr", code)
        for p in e.parts:
            if p.expr is None:
                pieces.append(("text", p.text))
                continue
            if p.debug:
                pieces.append(("text", p.text + "="))
            code = self.x(p.expr, P_LAMBDA + 1)
            ty = p.expr.ty
            spec = p.spec
            if spec:
                if spec == "%" or spec.endswith("%"):
                    pieces.append(("expr", f"_rt.fmt({code}, {spec!r})"))
                    continue
                if re.fullmatch(r"[<>^=]?\+?0?\d*,?\.\d+", spec) and ty is not None and not T.is_int(ty):
                    spec += "f"
                pieces.append(("spec", f"{code}:{spec}" if '"' not in code and "\\" not in code else
                               f"_rt.fmt({code}, {spec!r})"))
                continue
            if ty is not None and ty.kind == "duration":
                code = f"_rt.show_duration({code})"
            elif ty is not None and (ty.kind in self._NEEDS_SHOW or (ty.kind == "class")):
                code = f"_rt.show({code})"
            pieces.append(("expr", code))
        if all(k == "text" for k, _ in pieces):
            return repr("".join(v for _, v in pieces)), P_ATOM
        bad = any(("\\" in v or '"' in v or "{" in v and k != "text") for k, v in pieces if k != "text")
        if bad:
            parts = []
            for k, v in pieces:
                if k == "text":
                    parts.append(repr(v))
                elif k == "spec":
                    code, spec = v.rsplit(":", 1)
                    parts.append(f"format({code}, {spec!r})")
                else:
                    parts.append(f"_rt.show({v})" if not v.startswith("_rt.show(") else v)
            return '"".join((' + ", ".join(parts) + ",))", P_POSTFIX
        body = []
        for k, v in pieces:
            if k == "text":
                body.append(v.replace("\\", "\\\\").replace("{", "{{").replace("}", "}}")
                            .replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r"))
            else:
                body.append("{" + v + "}")
        return 'f"' + "".join(body) + '"', P_ATOM

    def ex_ListLit(self, e: A.ListLit):
        return "[" + ", ".join(self.store(i) for i in e.items) + "]", P_ATOM

    def ex_SetLit(self, e: A.SetLit):
        if not e.items:
            return "set()", P_POSTFIX
        return "{" + ", ".join(self.x(i, P_LAMBDA + 1) for i in e.items) + "}", P_ATOM

    def ex_MapLit(self, e: A.MapLit):
        return "{" + ", ".join(f"{self.x(k, P_LAMBDA + 1)}: {self.store(v)}" for k, v in e.pairs) + "}", P_ATOM

    def ex_EmptyBraces(self, e: A.EmptyBraces):
        return ("{}", P_ATOM) if e.as_map else ("set()", P_POSTFIX)

    def ex_TupleLit(self, e: A.TupleLit):
        if not e.items:
            return "()", P_ATOM
        if len(e.items) == 1:
            return f"({self.store(e.items[0])},)", P_ATOM
        return "(" + ", ".join(self.store(i) for i in e.items) + ")", P_ATOM

    def ex_Comprehension(self, e: A.Comprehension):
        var = self.name_for(e.var_sym)
        cond = f" if {self.x(e.cond, P_OR)}" if e.cond is not None else ""
        return f"[{self.x(e.expr, P_LAMBDA + 1)} for {var} in {self.iter_code(e.iterable)}{cond}]", P_ATOM

    # ---- names -------------------------------------------------------------
    def ex_Name(self, e: A.Name):
        sym = e.sym
        if sym is None:
            return mangle(e.id), P_ATOM
        if sym.kind == "class":
            real = sym.cls.name if getattr(sym, "cls", None) is not None else e.id
            return (f"_rt.{real}" if real in _ERROR_CLASSES else real), P_ATOM
        if sym.kind == "stdconst":
            return f"{sym.std_owner}.{mangle(sym.std_name)}", P_POSTFIX
        if sym.kind == "func":
            return mangle(e.id), P_ATOM
        return self.name_for(sym), P_ATOM

    def ex_This(self, e):
        return "self", P_ATOM

    def ex_Super(self, e):
        return "super()", P_POSTFIX

    # ---- operators ---------------------------------------------------------
    def ex_Unary(self, e: A.Unary):
        if e.op == "not":
            return f"not {self.x(e.operand, P_NOT)}", P_NOT
        code = f"{e.op}{self.x(e.operand, P_UNARY)}"
        if e.op == "-" and e.ty is not None and T.is_int(e.ty):
            return self.int_check(code, e.ty), P_POSTFIX if self.overflow else P_UNARY
        return code, P_UNARY

    def ex_Binary(self, e: A.Binary):
        code = self.binary_code(e)
        prec = P_POSTFIX if code.startswith("_rt.") else _BIN[e.op][1]
        return code, prec

    @staticmethod
    def _nonzero_literal(e: A.Expr) -> bool:
        return isinstance(e, (A.IntLit, A.FloatLit)) and e.value != 0

    def binary_code(self, e: A.Binary, cur_code: Optional[str] = None) -> str:
        op = e.op
        lt = e.left.ty
        rt = e.right.ty
        pyop, prec = _BIN[op]
        if lt is not None and lt.kind == "set" and op == "^":
            pyop = "^"
        right_prec = prec + 1 if op != "**" else prec
        left_prec = prec if op != "**" else prec + 1
        left = cur_code if cur_code is not None else self.x(e.left, left_prec)
        right = self.x(e.right, right_prec)
        if op == "/" and not self._nonzero_literal(e.right):
            return f"_rt.div({self.x(e.left, P_LAMBDA + 1) if cur_code is None else cur_code}, {self.x(e.right, P_LAMBDA + 1)})"
        if op == "~/" and not self._nonzero_literal(e.right):
            return f"_rt.floordiv({self.x(e.left, P_LAMBDA + 1) if cur_code is None else cur_code}, {self.x(e.right, P_LAMBDA + 1)})"
        if op == "%" and not self._nonzero_literal(e.right) and lt is not None and T.is_numeric(lt):
            return f"_rt.mod({self.x(e.left, P_LAMBDA + 1) if cur_code is None else cur_code}, {self.x(e.right, P_LAMBDA + 1)})"
        if op == "+" and lt is not None and T.is_seq(lt) and rt is not None and T.is_seq(rt):
            return f"{left} + {right}"
        code = f"{left} {pyop} {right}"
        if op in ("+", "-", "*", "**", "<<") and e.ty is not None and T.is_int(e.ty):
            return self.int_check(code, e.ty)
        return code

    def ex_Compare(self, e: A.Compare):
        parts = [self.x(e.operands[0], P_CMP + 1)]
        for op, operand in zip(e.ops, e.operands[1:]):
            if isinstance(operand, A.NoneLit) or isinstance(e.operands[0], A.NoneLit) and len(e.ops) == 1:
                pyop = "is" if op == "==" else ("is not" if op == "!=" else op)
            elif op == "===":
                pyop = "is"
            else:
                pyop = op
            if op in ("in", "not in") and isinstance(operand, A.RangeExpr):
                parts.append(f"{pyop} {self.range_code(operand)}")
            else:
                parts.append(f"{pyop} {self.x(operand, P_CMP + 1)}")
        return " ".join(parts), P_CMP

    def ex_Logical(self, e: A.Logical):
        p = P_AND if e.op == "and" else P_OR
        return f"{self.x(e.left, p)} {e.op} {self.x(e.right, p + 1)}", p

    def range_code(self, r: A.RangeExpr) -> str:
        if r.start is None or r.end is None:
            self.unsupported("an open-ended range outside of [ ]", r.span)
            return "range(0)"
        s = self.x(r.start, P_LAMBDA + 1)
        step = r.step
        if not r.inclusive:
            if step is None:
                return f"range({s}, {self.x(r.end, P_LAMBDA + 1)})"
            return f"range({s}, {self.x(r.end, P_LAMBDA + 1)}, {self.x(step, P_LAMBDA + 1)})"
        if step is None:
            return f"range({s}, {self.x(r.end, P_ADD)} + 1)"
        if isinstance(step, A.IntLit):
            adj = " + 1" if step.value > 0 else " - 1"
            return f"range({s}, {self.x(r.end, P_ADD)}{adj}, {step.value})"
        return f"_rt.irange({s}, {self.x(r.end, P_LAMBDA + 1)}, {self.x(step, P_LAMBDA + 1)})"

    def slice_code(self, r: A.RangeExpr) -> str:
        s = self.x(r.start, P_LAMBDA + 1) if r.start is not None else ""
        if r.end is None:
            end = ""
        elif r.inclusive:
            end = f"{self.x(r.end, P_ADD)} + 1"
        else:
            end = self.x(r.end, P_LAMBDA + 1)
        step = f":{self.x(r.step, P_LAMBDA + 1)}" if r.step is not None else ""
        return f"{s}:{end}{step}"

    def ex_RangeExpr(self, e: A.RangeExpr):
        if e.ty is not None and T.is_seq(e.ty):
            return f"list({self.range_code(e)})", P_POSTFIX
        return self.range_code(e), P_POSTFIX

    def ex_Coalesce(self, e: A.Coalesce):
        left = e.left
        if isinstance(left, A.Call) and getattr(left, "fails", None):
            return (f"_rt.try_or(lambda: {self.x(left, P_LAMBDA)}, lambda: {self.x(e.right, P_LAMBDA)})",
                    P_POSTFIX)
        if left.ty is not None and left.ty.kind == "result":
            return f"{self.x(left, P_POSTFIX)}.get_or({self.x(e.right, P_LAMBDA + 1)})", P_POSTFIX
        t = self.temp("v")
        return (f"{t} if ({t} := {self.x(left, P_LAMBDA + 1)}) is not None else {self.x(e.right, P_IF)}",
                P_IF)

    def ex_IfExpr(self, e: A.IfExpr):
        return (f"{self.x(e.then, P_IF + 1)} if {self.x(e.cond, P_IF + 1)} else {self.x(e.else_, P_IF)}",
                P_IF)

    def ex_TypeTest(self, e: A.TypeTest):
        self.unsupported("`is <type>`", e.span)
        return "False", P_ATOM

    def ex_Cast(self, e: A.Cast):
        src = e.expr.ty
        dst = e.ty if e.mode != "as?" else e.ty.args[0]
        code = self.x(e.expr, P_LAMBDA + 1)
        if src == dst:
            return code, P_ATOM
        fn = {"as": "cast", "as?": "try_cast", "as!": "wrap"}[e.mode]
        if T.is_float(dst) and e.mode == "as":
            return f"float({code})", P_POSTFIX
        kind = dst.kind
        return f"_rt.{fn}({code}, {kind!r})", P_POSTFIX

    def ex_Propagate(self, e: A.Propagate):
        inner = e.expr
        if inner.ty is not None and inner.ty.kind == "result":
            return f"{self.x(inner, P_POSTFIX)}.unwrap()", P_POSTFIX
        return self.ex(inner)

    def ex_SwitchExpr(self, e: A.SwitchExpr):
        s = e.switch
        if any(len(c.body) != 1 or not isinstance(c.body[0], A.ExprStmt) for c in s.cases):
            self.unsupported("a switch used as a value with statements before its value", e.span)
            return "None", P_ATOM
        subj = s.subject
        bind = ""
        if not isinstance(subj, (A.Name, A.IntLit, A.StrLit, A.This)):
            t = self.temp("s")
            bind = t
            self.node_subst[id(subj)] = t
        code = None
        for c in reversed(s.cases):
            val = self.x(c.body[0].expr, P_IF + 1)
            if c.patterns is None:
                code = val
            else:
                cond = " or ".join(self.x(cc, P_OR + 1) for cc in c.conds)
                code = f"{val} if {cond} else {code if code is not None else 'None'}"
        self.node_subst.pop(id(subj), None)
        if bind:
            code = f"({bind} := {self.x(subj, P_LAMBDA + 1)}, {code})[1]"
            return code, P_POSTFIX
        return code or "None", P_IF

    def ex_Lambda(self, e: A.Lambda):
        if isinstance(e.body, A.Block):
            self.unsupported("Function(...) { ... } with a block body used as a value", e.span)
            return "None", P_ATOM
        params = ", ".join(self.name_for(p.sym) for p in e.params)
        return f"lambda {params}: {self.x(e.body, P_LAMBDA)}", P_LAMBDA

    def ex_ImplicitFn(self, e: A.ImplicitFn):
        return self.x(e.body, P_LAMBDA), P_LAMBDA

    # ---- member / index ------------------------------------------------------
    def ex_Member(self, e: A.Member):
        obj_t = e.obj.ty
        if e.safe:
            t = self.temp("v")
            inner = A.Member(e.span, A.Name(e.span, t), e.name)
            inner.field_info = e.field_info
            inner.obj.ty = obj_t.args[0] if obj_t is not None and obj_t.kind == "maybe" else obj_t
            self.node_subst[id(inner.obj)] = t
            body = self.ex_Member_plain(inner)
            self.node_subst.pop(id(inner.obj), None)
            return f"None if ({t} := {self.x(e.obj, P_LAMBDA + 1)}) is None else {body}", P_IF
        return self.ex_Member_plain(e), P_POSTFIX

    def ex_Member_plain(self, e: A.Member) -> str:
        obj_t = e.obj.ty
        obj = self.x(e.obj, P_POSTFIX)
        if obj_t is not None and obj_t.kind == "tuple" and e.name.isdigit():
            return f"{obj}[{e.name}]"
        return f"{obj}.{mangle(e.name)}"

    def ex_Index(self, e: A.Index):
        obj = self.x(e.obj, P_POSTFIX)
        if isinstance(e.index, A.RangeExpr):
            return f"{obj}[{self.slice_code(e.index)}]", P_POSTFIX
        ot = e.obj.ty
        if ot is not None and ot.kind == "map" and isinstance(e.obj, A.Name) and e.obj.sym is not None:
            d = e.obj.sym.annots.get("default") if hasattr(e.obj.sym, "annots") else None
            if d is not None and d.args:
                return f"{obj}.get({self.x(e.index, P_LAMBDA + 1)}, {self.x(d.args[0], P_LAMBDA + 1)})", P_POSTFIX
        return f"{obj}[{self.x(e.index, P_LAMBDA)}]", P_POSTFIX

    # ==================================================================
    # Calls
    # ==================================================================
    def args_code(self, e: A.Call, params: list[T.ParamInfo]) -> str:
        parts: list[str] = []
        keyword_mode = False
        for p in params:
            if p.variadic:
                for v in getattr(e, "_variadic", []):
                    parts.append(self.x(v, P_LAMBDA + 1))
                continue
            if p.name not in e.bound:
                keyword_mode = True
                continue
            v = self.x(e.bound[p.name], P_LAMBDA + 1)
            parts.append(f"{mangle(p.name)}={v}" if keyword_mode else v)
        return ", ".join(parts)

    def ex_Call(self, e: A.Call):
        k = e.kind
        if k == "builtin":
            return self.builtin_code(e), P_POSTFIX
        if k == "cast":
            return self.ex(e.target)
        if k == "func":
            fi: T.FuncInfo = e.target
            return f"{mangle(fi.name)}({self.args_code(e, fi.params)})", P_POSTFIX
        if k == "value":
            return f"{self.x(e.func, P_POSTFIX)}({', '.join(self.x(a.value, P_LAMBDA + 1) for a in e.args)})", P_POSTFIX
        if k == "ctor":
            ci, chosen = e.target
            ref = f"_rt.{ci.name}" if ci.name in _ERROR_CLASSES else ci.name
            explicit = [c for c in ci.ctors if c.decl is not None]
            args = self.args_code(e, chosen.params) if chosen is not None else ""
            if chosen is not None and chosen.decl is not None and len(explicit) > 1:
                return f"{ref}.{mangle(chosen.decl.name)}({args})", P_POSTFIX
            return f"{ref}({args})", P_POSTFIX
        if k in ("method", "super"):
            fi = e.target
            obj = self.x(e.func.obj, P_POSTFIX)
            return f"{obj}.{mangle(fi.name)}({self.args_code(e, fi.params)})", P_POSTFIX
        if k == "static":
            fi = e.target
            return f"{fi.owner}.{mangle(fi.name)}({self.args_code(e, fi.params)})", P_POSTFIX
        if k == "bank":
            return self.bank_expr(e), P_POSTFIX
        self.unsupported("this call", e.span)
        return "None", P_ATOM

    def builtin_code(self, e: A.Call) -> str:
        name = e.target
        pos = [a.value for a in e.args if a.name is None]
        named = {a.name: a.value for a in e.args if a.name is not None}
        a = [self.x(v, P_LAMBDA + 1) for v in pos]
        if name == "print":
            extra = "".join(f", {k}={self.x(v, P_LAMBDA + 1)}" for k, v in named.items())
            shown = [f"_rt.show_duration({c})" if v.ty is not None and v.ty.kind == "duration" else c
                     for c, v in zip(a, pos)]
            return f"_rt.fx_print({', '.join(shown)}{extra})"
        if name == "sleep":
            return f"_rt.sleep({a[0]})"
        if name == "input":
            return f"input({a[0] if a else ''})"
        if name == "len":
            return f"len({a[0]})"
        if name in ("min", "max"):
            if len(pos) == 1:
                return f"_rt.{'minimum' if name == 'min' else 'maximum'}({a[0]})"
            return f"{name}({', '.join(a)})"
        if name == "abs":
            return f"abs({a[0]})"
        if name == "round":
            digits = named.get("digits")
            if len(a) > 1:
                return f"_rt.round({a[0]}, {a[1]})"
            if digits is not None:
                return f"_rt.round({a[0]}, {self.x(digits, P_LAMBDA + 1)})"
            return f"_rt.round({a[0]})"
        if name in ("floor", "ceil"):
            return f"_rt.{name}({a[0]})"
        if name == "sum":
            return self.int_check(f"sum({a[0]})", e.ty)
        if name == "sorted":
            return f"sorted({a[0]})"
        if name == "range":
            return f"range({', '.join(a)})"
        if name == "panic":
            return f"_rt.panic({a[0] if a else repr('panic')})"
        if name == "unreachable":
            return "_rt.panic('unreachable code was reached')"
        if name == "ensure":
            msg = a[1] if len(a) > 1 else repr("ensure failed")
            return f"_rt.ensure({a[0]}, {msg})"
        if name == "string":
            return f"_rt.show({a[0]})"
        if name == "exit":
            return f"_rt.exit({a[0] if a else '0'})"
        self.unsupported(f"built-in `{name}`", e.span)
        return "None"

    # ---- bank methods ----------------------------------------------------------
    def _implicit(self, fn: A.Expr, mapping: dict[str, str]) -> str:
        """Code for an implicit-variable argument, with currVal / index / ... replaced."""
        if not isinstance(fn, A.ImplicitFn):
            return self.x(fn, P_LAMBDA + 1)
        for name, sym in fn.syms.items():
            if name in mapping:
                self.subst[id(sym)] = mapping[name]
        code = self.x(fn.body, P_LAMBDA + 1)
        for sym in fn.syms.values():
            self.subst.pop(id(sym), None)
        return code

    @staticmethod
    def _uses(fn: Optional[A.Expr], *names: str) -> bool:
        return isinstance(fn, A.ImplicitFn) and any(n in fn.params for n in names)

    def _seq_comp(self, recv: str, fn: A.Expr, value_code_fn) -> tuple[str, dict]:
        """Loop header and mapping for a comprehension over a list, given which implicit names are used."""
        if self._uses(fn, "prevVal", "nextVal"):
            return (f"for index, currVal, prevVal, nextVal in _rt.neighbours({recv})",
                    {"currVal": "currVal", "index": "index", "prevVal": "prevVal", "nextVal": "nextVal"})
        if self._uses(fn, "index"):
            return f"for index, currVal in enumerate({recv})", {"currVal": "currVal", "index": "index"}
        return f"for currVal in {recv}", {"currVal": "currVal"}

    def _map_comp(self, recv: str, fn: Optional[A.Expr] = None) -> tuple[str, dict]:
        # if a user variable called `key` is visible, the implicit one doesn't exist:
        # bind the loop key under another name so the user's variable isn't hidden
        k = "key" if not isinstance(fn, A.ImplicitFn) or "key" in fn.syms else "_key"
        return f"for {k}, currVal in {recv}.items()", {"currVal": "currVal", "key": k}

    def _comp(self, kind: str, recv: str, fn: A.Expr) -> tuple[str, dict]:
        if kind == "map":
            return self._map_comp(recv, fn)
        if kind == "set":
            return f"for currVal in {recv}", {"currVal": "currVal"}
        return self._seq_comp(recv, fn, None)

    def _index_values(self, idx: A.Expr, recv: str) -> str:
        if isinstance(idx, A.RangeExpr):
            if idx.end is None:
                start = self.x(idx.start, P_LAMBDA + 1) if idx.start is not None else "0"
                return f"range({start}, len({recv}))"
            if idx.start is None:
                end = self.x(idx.end, P_ADD) + (" + 1" if idx.inclusive else "")
                return f"range(0, {end})"
            return self.range_code(idx)
        if idx.ty is not None and T.is_seq(idx.ty):
            return self.x(idx, P_LAMBDA + 1)
        return f"[{self.x(idx, P_LAMBDA + 1)}]"

    def bank_stmt(self, e: A.Call) -> bool:
        """Actions that are clearest as statements. Returns False to fall back to bank_expr."""
        c = e.target
        b = e.bound
        recv_t: Ty = e.recv_ty
        kind = T.receiver_kind(recv_t)
        recv = self.x(e.func.obj, P_POSTFIX)
        if c == "modifyAt":
            cond = b.get("condition")
            newv = b["newVal"]
            if kind == "map":
                key = b.get("key")
                default = b.get("default")
                if default is None and isinstance(e.func.obj, A.Name) and e.func.obj.sym is not None:
                    d = e.func.obj.sym.annots.get("default")
                    if d is not None and d.args:
                        default = d.args[0]
                if key is not None:
                    k = self.temp("k")
                    self.line(f"{k} = {self.x(key, P_LAMBDA + 1)}")
                    if default is not None:
                        self.line(f"if {k} not in {recv}:")
                        self.indent()
                        self.line(f"{recv}[{k}] = {self.store(default)}")
                        self.dedent()
                    v = self.temp("v")
                    self.line(f"{v} = {recv}[{k}]")
                    mapping = {"currVal": v, "key": k}
                    if cond is not None:
                        self.line(f"if {self._implicit(cond, mapping)}:")
                        self.indent()
                        self.line(f"{recv}[{k}] = {self._implicit(newv, mapping)}")
                        self.dedent()
                    else:
                        self.line(f"{recv}[{k}] = {self._implicit(newv, mapping)}")
                    return True
                k, v = self.temp("k"), self.temp("v")
                mapping = {"currVal": v, "key": k}
                self.line(f"for {k}, {v} in list({recv}.items()):")
                self.indent()
                if cond is not None:
                    self.line(f"if {self._implicit(cond, mapping)}:")
                    self.indent()
                    self.line(f"{recv}[{k}] = {self._implicit(newv, mapping)}")
                    self.dedent()
                else:
                    self.line(f"{recv}[{k}] = {self._implicit(newv, mapping)}")
                self.dedent()
                return True
            i, v = self.temp("i"), self.temp("v")
            idx = b.get("index")
            indices = self._index_values(idx, recv) if idx is not None else f"range(len({recv}))"
            mapping = {"currVal": v, "index": i,
                       "prevVal": f"({recv}[{i} - 1] if {i} > 0 else None)",
                       "nextVal": f"({recv}[{i} + 1] if {i} + 1 < len({recv}) else None)"}
            self.line(f"for {i} in {indices}:")
            self.indent()
            self.line(f"{v} = {recv}[{i}]")
            if cond is not None:
                self.line(f"if {self._implicit(cond, mapping)}:")
                self.indent()
                self.line(f"{recv}[{i}] = {self._implicit(newv, mapping)}")
                self.dedent()
            else:
                self.line(f"{recv}[{i}] = {self._implicit(newv, mapping)}")
            self.dedent()
            return True
        if c == "removeWhere":
            cond = b["condition"]
            if kind == "map":
                header, mapping = self._map_comp(recv, cond)
                k = self.temp("k")
                self.line(f"for {k} in [{mapping['key']} {header} if {self._implicit(cond, mapping)}]:")
                self.indent()
                self.line(f"del {recv}[{k}]")
                self.dedent()
                return True
            header, mapping = self._comp(kind, recv, cond)
            if kind == "set":
                self.line(f"{recv}.difference_update({{currVal {header} if {self._implicit(cond, mapping)}}})")
                return True
            self.line(f"{recv}[:] = [currVal {header} if not ({self._implicit(cond, mapping)})]")
            return True
        if c == "fill" and "index" in b:
            i = self.temp("i")
            self.line(f"for {i} in {self._index_values(b['index'], recv)}:")
            self.indent()
            self.line(f"{recv}[{i}] = {self.store(b['value'])}")
            self.dedent()
            return True
        if c == "swap":
            i, j = self.x(b["index"], P_LAMBDA + 1), self.x(b["other"], P_LAMBDA + 1)
            self.line(f"{recv}[{i}], {recv}[{j}] = {recv}[{j}], {recv}[{i}]")
            return True
        if c == "set":
            key = b.get("key") or b.get("index")
            self.line(f"{recv}[{self.x(key, P_LAMBDA)}] = {self.store(b['value'])}")
            return True
        if c == "removeAt":
            idx = b["index"]
            if isinstance(idx, A.RangeExpr):
                self.line(f"del {recv}[{self.slice_code(idx)}]")
            else:
                self.line(f"del {recv}[{self.x(idx, P_LAMBDA)}]")
            return True
        if c == "remove" and kind == "seq" and "all" in b:
            v = self.x(b["value"], P_CMP + 1)
            if isinstance(b["all"], A.BoolLit) and b["all"].value:
                self.line(f"{recv}[:] = [x for x in {recv} if x != {v}]")
                return True
        if c == "replace" and kind == "seq":
            old, new = self.x(b["old"], P_CMP + 1), self.store(b["newVal"])
            self.line(f"{recv}[:] = [{new} if x == {old} else x for x in {recv}]")
            return True
        return False

    def bank_expr(self, e: A.Call) -> str:
        c = e.target
        b = e.bound
        recv_t: Ty = e.recv_ty
        kind = T.receiver_kind(recv_t)
        obj = e.func.obj
        recv = self.x(obj, P_POSTFIX)
        safe = e.func.safe
        if safe:
            t = self.temp("v")
            inner_recv = t
            code = self._bank_expr_inner(e, c, b, recv_t.args[0] if recv_t.kind == "maybe" else recv_t,
                                         T.receiver_kind(recv_t.args[0]) if recv_t.kind == "maybe" else kind,
                                         inner_recv)
            return f"(None if ({t} := {self.x(obj, P_LAMBDA + 1)}) is None else {code})"
        return self._bank_expr_inner(e, c, b, recv_t, kind, recv)

    def _bank_expr_inner(self, e: A.Call, c: str, b: dict, recv_t: Ty, kind: str, recv: str) -> str:
        X = lambda name, p=P_LAMBDA + 1: self.x(b[name], p)  # noqa: E731
        if c == "size":
            return f"len({recv})"
        if c == "isEmpty":
            return f"(len({recv}) == 0)"
        if c == "get":
            if kind == "map":
                return f"{recv}[{X('key', P_LAMBDA)}]"
            idx = b["index"]
            if isinstance(idx, A.RangeExpr):
                return f"{recv}[{self.slice_code(idx)}]"
            return f"{recv}[{self.x(idx, P_LAMBDA)}]"
        if c == "getOr":
            if kind == "maybe":
                t = self.temp("v")
                return f"({t} if ({t} := {recv}) is not None else {X('default', P_IF)})"
            if kind == "result":
                return f"{recv}.get_or({X('default')})"
            if kind == "map":
                return f"{recv}.get({X('key')}, {X('default')})"
            return f"_rt.get_or({recv}, {X('index')}, {X('default')})"
        if c in ("first", "last", "pop"):
            return f"_rt.{c}({recv})"
        if c == "popFront":
            return f"_rt.pop_front({recv})"
        if c == "slice":
            idx = b["index"]
            if isinstance(idx, A.RangeExpr):
                return f"{recv}[{self.slice_code(idx)}]"
            return f"{recv}[{self.x(idx, P_LAMBDA)}]"
        if c == "keys":
            return f"list({recv}.keys())"
        if c == "values":
            return f"list({recv}.values())"
        if c in ("items",):
            return f"list({recv}.items())"
        if c == "add":
            if kind == "set":
                return f"{recv}.add({X('value')})"
            if "index" in b:
                return f"{recv}.insert({X('index')}, {self.store(b['value'])})"
            return f"{recv}.append({self.store(b['value'])})"
        if c == "addAll":
            if kind == "set":
                return f"{recv}.update({X('values')})"
            return f"{recv}.extend({self.store(b['values'])})"
        if c == "remove":
            if kind == "set":
                return f"{recv}.discard({X('value')})"
            if kind == "map":
                return f"{recv}.pop({X('key')}, None)"
            return f"_rt.remove_first({recv}, {X('value')})"
        if c == "clear":
            return f"{recv}.clear()"
        if c == "fill":
            return f"{recv}.__setitem__(slice(None), [{X('value')}] * len({recv}))"
        if c == "sort":
            return f"{recv}.sort({self._sort_args(b)})".replace("(, ", "(")
        if c == "sorted":
            args = self._sort_args(b)
            return f"sorted({recv}{(', ' + args) if args else ''})"
        if c == "reverse":
            if kind == "string":
                return f"{recv}[::-1]"
            return f"{recv}.reverse()"
        if c == "reversed":
            return f"{recv}[::-1]"
        if c == "dedupe":
            return f"{recv}.__setitem__(slice(None), list(dict.fromkeys({recv})))"
        if c == "contains":
            if "condition" in b:
                header, mapping = self._comp(kind, recv, b["condition"])
                return f"any({self._implicit(b['condition'], mapping)} {header})"
            key = b.get("key") or b.get("value")
            return f"({self.x(key, P_CMP + 1)} in {recv})"
        if c == "indexOf":
            if kind == "string":
                return f"_rt.str_index({recv}, {X('value')})"
            if "condition" in b:
                fn = b["condition"]
                if self._uses(fn, "prevVal", "nextVal"):
                    header = f"for index, currVal, prevVal, nextVal in _rt.neighbours({recv})"
                    mapping = {"currVal": "currVal", "index": "index", "prevVal": "prevVal", "nextVal": "nextVal"}
                else:
                    header = f"for index, currVal in enumerate({recv})"
                    mapping = {"currVal": "currVal", "index": "index"}
                return f"next((index {header} if {self._implicit(fn, mapping)}), None)"
            return f"_rt.index_of({recv}, {X('value')})"
        if c == "find":
            header, mapping = self._comp(kind, recv, b["condition"])
            return f"next((currVal {header} if {self._implicit(b['condition'], mapping)}), None)"
        if c == "count":
            if kind == "string":
                return f"{recv}.count({X('value')})"
            if "condition" in b:
                header, mapping = self._comp(kind, recv, b["condition"])
                return f"sum(1 {header} if {self._implicit(b['condition'], mapping)})"
            if kind == "set":
                return f"(1 if {X('value', P_CMP + 1)} in {recv} else 0)"
            if kind == "map":
                return f"list({recv}.values()).count({X('value')})"
            return f"{recv}.count({X('value')})"
        if c in ("any", "all"):
            header, mapping = self._comp(kind, recv, b["condition"])
            return f"{c}({self._implicit(b['condition'], mapping)} {header})"
        if c == "min":
            return f"_rt.minimum({recv})"
        if c == "max":
            return f"_rt.maximum({recv})"
        if c == "sum":
            return self.int_check(f"sum({recv})", e.ty)
        if c == "average":
            return f"_rt.average({recv})"
        if c == "filter":
            fn = b["condition"]
            header, mapping = self._comp(kind, recv, fn)
            cond = self._implicit(fn, mapping)
            if kind == "map":
                return f"{{{mapping['key']}: currVal {header} if {cond}}}"
            if kind == "set":
                return f"{{currVal {header} if {cond}}}"
            return f"[currVal {header} if {cond}]"
        if c == "map":
            fn = b["newVal"]
            header, mapping = self._comp(kind, recv, fn)
            val = self._implicit(fn, mapping)
            if kind == "map":
                return f"{{{mapping['key']}: {val} {header}}}"
            if kind == "set":
                return f"{{{val} {header}}}"
            return f"[{val} {header}]"
        if c == "reduce":
            fn = b["newVal"]
            if self._uses(fn, "index"):
                pair = self.temp("p")
                mapping = {"acc": "acc", "currVal": f"{pair}[1]", "index": f"{pair}[0]"}
                lam = f"lambda acc, {pair}: {self._implicit(fn, mapping)}"
                it = f"list(enumerate({recv}))"
            else:
                mapping = {"acc": "acc", "currVal": "currVal"}
                lam = f"lambda acc, currVal: {self._implicit(fn, mapping)}"
                it = recv
            start = f", {X('start')}" if "start" in b else ""
            return f"_rt.reduce({lam}, {it}{start})"
        if c == "take":
            return f"{recv}[:{X('count', P_LAMBDA)}]"
        if c == "skip":
            return f"{recv}[{X('count', P_LAMBDA)}:]"
        if c == "join":
            if kind == "string":
                vals = b.get("values")
                items = self.x(vals, P_LAMBDA + 1) if vals is not None else "[]"
