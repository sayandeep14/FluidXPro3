"""`fluid package <file>`: what a deployment needs, in one folder (ROADMAP E-19).

    build/package/
        app/             the generated program (with fx3rt.py / fx3std.py) and requirements.txt
        app.pyz          the same program as one runnable file: python app.pyz
        Dockerfile       slim Python image, non-root user, health check, SERVER_HOST=0.0.0.0
        .env.example     the environment variables the program reads: names only, never values
        .dockerignore

Nothing is copied from the project folder itself, so secrets.env can't end up in a package.
"""

from __future__ import annotations

import re
import shutil
import zipapp
from dataclasses import dataclass, field
from pathlib import Path

ENV_RE = re.compile(r"""\bEnv\.(?:get|require|has)\(\s*['"]([A-Za-z_][A-Za-z0-9_]*)['"]""")
HEALTH_RE = re.compile(r"""\.get\(\s*['"]/health['"]""")
PYTHON_IMAGE = "python:3.12-slim"
NEVER_PACKAGED = {"secrets.env", ".env", "fluid.lock"}


@dataclass
class Package:
    folder: Path
    entry: str
    env: list[tuple[str, str]] = field(default_factory=list)     # (name, what it is)
    server: bool = False
    health: bool = False
    files: list[str] = field(default_factory=list)


def env_names(code: str, secrets: list[str]) -> list[tuple[str, str]]:
    """The variables a program reads, with a note each. `secrets`: names from the .fluid `secrets` block."""
    out: dict[str, str] = {}
    for name in secrets:
        out[name] = "secret"
    for name in ENV_RE.findall(code):
        out.setdefault(name, "read by the program")
    if "Server.create(" in code:
        out.setdefault("SERVER_HOST", "address to listen on (the Dockerfile sets 0.0.0.0)")
        out.setdefault("SERVER_PORT", "port to listen on")
    if "Schedule.every(" in code:
        out.setdefault("SCHEDULE_STATE", "file that keeps the last run of each job (default .fx3-schedule.json)")
    if "Email.send(" in code:
        for name in ("SMTP_HOST", "SMTP_PORT", "SMTP_USER", "SMTP_PASSWORD", "SMTP_FROM"):
            out.setdefault(name, "email server")
    if "Ai.ask(" in code or "Ai.classify(" in code:
        out.setdefault("ANTHROPIC_API_KEY", "secret")
    return sorted(out.items())


def dockerfile(entry: str, requirements: bool, server: bool, health: bool, port: int = 8080) -> str:
    lines = [
        "# Generated by `fluid package`. Build: docker build -t my-app .   Run: docker run --env-file .env my-app",
        f"FROM {PYTHON_IMAGE}",
        "ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1",
        "RUN useradd --create-home --uid 10001 app",
        "WORKDIR /app",
    ]
    if requirements:
        lines += ["COPY app/requirements.txt .",
                  "RUN pip install --no-cache-dir -r requirements.txt"]
    lines += ["COPY app/ .", "USER app"]
    if server:
        lines += [f"ENV SERVER_HOST=0.0.0.0 SERVER_PORT={port}", f"EXPOSE {port}"]
        if health:
            probe = ("import os, urllib.request; "
                     "urllib.request.urlopen(f'http://127.0.0.1:{os.environ[\"SERVER_PORT\"]}/health', timeout=3)")
        else:
            probe = "import os, socket; socket.create_connection(('127.0.0.1', int(os.environ['SERVER_PORT'])), 3)"
        lines += [f'HEALTHCHECK --interval=30s --timeout=5s --retries=3 CMD ["python", "-c", "{_q(probe)}"]']
    lines += ["STOPSIGNAL SIGTERM", f'CMD ["python", "{entry}"]']
    return "\n".join(lines) + "\n"


def _q(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def create(files: dict[str, str], entry: str, out: Path, secrets: list[str]) -> Package:
    """Write the package for a built program (`files`: the generated files, by relative path)."""
    if out.exists():
        shutil.rmtree(out)
    app = out / "app"
    app.mkdir(parents=True)
    for rel, text in files.items():
        if Path(rel).name in NEVER_PACKAGED:
            raise ValueError(f"refusing to package {rel}")
        p = app / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    code = "\n".join(t for r, t in files.items() if r.endswith(".py") and r not in ("fx3rt.py", "fx3std.py"))
    pkg = Package(out, entry, env_names(code, secrets), "Server.create(" in code, bool(HEALTH_RE.search(code)))
    reqs = files.get("requirements.txt", "")
    needs = any(line.strip() and not line.startswith("#") for line in reqs.splitlines())

    (out / "Dockerfile").write_text(dockerfile(entry, needs, pkg.server, pkg.health), encoding="utf-8")
    (out / ".dockerignore").write_text("*\n!app/\n", encoding="utf-8")
    env_lines = ["# The environment this program reads. Copy to .env and fill in the values;",
                 "# keep .env out of version control. Names only: fluid package never writes values."]
    env_lines += [f"{name}=    # {what}" for name, what in pkg.env]
    (out / ".env.example").write_text("\n".join(env_lines) + "\n", encoding="utf-8")

    main = app / "__main__.py"
    main.write_text(f"import runpy\nrunpy.run_module({Path(entry).stem!r}, run_name='__main__')\n", encoding="utf-8")
    zipapp.create_archive(app, out / "app.pyz", interpreter="/usr/bin/env python3")
    main.unlink()
    pkg.files = sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())
    return pkg
