"""The generated .fx3 file: one marked region per .fluid block (FLUID_SPEC.md section 5).

    // @from main.fluid:58 "to monthly summary" fluid=3fa1c2d4e5f6 fx3=9c2e11aa0b1c
    ...code...
    // @end "to monthly summary"

`fx3=` is the hash of the code as fluidc wrote it. If the code between the markers no longer
matches, someone edited it by hand, and fluidc keeps the edit.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass

MARK_RE = re.compile(r'^// @from (?P<file>\S+):(?P<line>\d+) "(?P<id>[^"]+)" fluid=(?P<fh>\w+) fx3=(?P<xh>\w+)\s*$')
END_RE = re.compile(r'^// @end "(?P<id>[^"]+)"\s*$')


def code_hash(code: str) -> str:
    norm = "\n".join(line.rstrip() for line in code.strip("\n").splitlines())
    return hashlib.sha256(norm.encode()).hexdigest()[:12]


@dataclass
class Region:
    id: str
    code: str
    recorded_hash: str      # fx3= on the marker
    fluid_hash: str
    edited: bool


def parse_existing(text: str) -> dict[str, Region]:
    out: dict[str, Region] = {}
    lines = text.splitlines()
    k = 0
    while k < len(lines):
        m = MARK_RE.match(lines[k])
        if not m:
            k += 1
            continue
        bid = m.group("id")
        j = k + 1
        body: list[str] = []
        while j < len(lines) and not (END_RE.match(lines[j]) and END_RE.match(lines[j]).group("id") == bid):
            body.append(lines[j])
            j += 1
        code = "\n".join(body)
        out[bid] = Region(bid, code, m.group("xh"), m.group("fh"), code_hash(code) != m.group("xh"))
        k = j + 1
    return out


@dataclass
class Assembled:
    text: str
    ranges: dict[str, tuple[int, int]]     # block id -> (first, last) line of its code (1-based)

    def block_at(self, line: int) -> str | None:
        for bid, (a, b) in self.ranges.items():
            if a <= line <= b:
                return bid
        return None


IMPORT_RE = re.compile(r"^\s*(import\s+\w+|from\s+\w+\s+import\s)")
IMPORTS_START = "// @imports (collected from every block; fluidc rewrites this part on each build)"
IMPORTS_END = "// @end imports"


def split_imports(code: str) -> tuple[list[str], str]:
    """Imports must come first in fx3, so they are lifted out of each block."""
    imports, rest = [], []
    for line in code.splitlines():
        (imports if IMPORT_RE.match(line) else rest).append(line.strip() if IMPORT_RE.match(line) else line)
    return imports, "\n".join(rest).strip("\n")


def existing_imports(text: str) -> list[str]:
    lines = text.splitlines()
    if IMPORTS_START in lines:
        start = lines.index(IMPORTS_START) + 1
        end = lines.index(IMPORTS_END) if IMPORTS_END in lines else start
        return [x.strip() for x in lines[start:end] if IMPORT_RE.match(x)]
    return []


def assemble(doc, codes: dict[str, str], recorded: dict[str, str], source_name: str,
             keep_imports: list[str] | None = None) -> Assembled:
    """codes: block id -> code to write. recorded: block id -> marker hash to keep (hand edits only;
    every other block gets the hash of the code written). keep_imports: imports already in the file."""
    out = [
        f"// Generated by fluidc from {source_name}. You can edit this file: fluidc keeps hand edits",
        "// (see FLUID_SPEC.md section 5). `fluidc pin <block>` copies an edit back into the .fluid file.",
        "",
    ]
    bodies: dict[str, str] = {}
    imports: list[str] = []
    for b in doc.blocks:
        if b.id in codes:
            found, bodies[b.id] = split_imports(codes[b.id])
            imports += found
    for imp in (keep_imports or []):
        imports.append(imp)
    unique = list(dict.fromkeys(imports))
    if unique:
        out += [IMPORTS_START, *unique, IMPORTS_END, ""]
    ranges: dict[str, tuple[int, int]] = {}
    for b in doc.blocks:
        if b.id not in codes:
            continue
        code = bodies[b.id]
        out.append(f'// @from {source_name}:{b.line_no} "{b.id}" fluid={b.fluid_hash} '
                   f'fx3={recorded.get(b.id, code_hash(code))}')
        start = len(out) + 1
        if code:
            out += code.splitlines()
        ranges[b.id] = (start, len(out))
        out.append(f'// @end "{b.id}"')
        out.append("")
    return Assembled("\n".join(out).rstrip() + "\n", ranges)
